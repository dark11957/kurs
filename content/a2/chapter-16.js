function collectExercises(value, result = []) {
  if (!value || typeof value !== "object") return result;
  if (Array.isArray(value)) { value.forEach(item => collectExercises(item, result)); return result; }
  if (typeof value.id === "string" && value.type && value.prompt) result.push(value);
  Object.values(value).forEach(item => collectExercises(item, result));
  return result;
}
